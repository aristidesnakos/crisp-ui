// Generates the agent-facing files from apps/v4/registry-crisp.template.json,
// so they cannot drift from the registry:
//
//   skills/crisp-ui/SKILL.md           an Agent Skill (https://agentskills.io/specification)
//   apps/v4/public/agents-snippet.md   a block to paste into AGENTS.md / CLAUDE.md,
//                                      also served at /agents-snippet.md
//   apps/v4/content/docs/ai.mdx        only the copy of that block between its
//                                      agents-snippet:start/end markers
//   registry.json                      the same items as a GitHub registry, so
//                                      `shadcn add owner/repo/item` works with no
//                                      hosting (https://ui.shadcn.com/docs/registry/github)
//
//   pnpm agent:build            write both files
//   node scripts/build-agent-files.mjs --check   exit 1 if they are out of date
//
// Not part of `pnpm registry:build`: the outputs are committed, and a build step
// that rewrites tracked files would hide drift from CI. tests/agent-files.test.ts
// fails when the committed files no longer match the template.
//
// UNVERIFIED: whether `npx skills add <owner>/<repo>` (skills.sh) or any other
// tool discovers a skill at `skills/crisp-ui/` in this repo. The Agent Skills
// spec says a skill is a directory containing SKILL.md whose name matches the
// directory; the repo layout each tool scans was not established, and Claude
// Code's documented project location is `.claude/skills/<name>/SKILL.md`. Do
// not document an install path for the skill until it has been tried.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

// Agent files always point at production, never at the localhost origin CI uses
// to build the registry.
export const PRODUCTION_ORIGIN = "https://regularui.com"

// The placeholder the template uses wherever the registry origin goes.
const ORIGIN_TOKEN = "__REGISTRY_ORIGIN__"

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const repoRoot = path.resolve(appRoot, "../..")
export const TEMPLATE_PATH = path.join(appRoot, "registry-crisp.template.json")
export const SKILL_PATH = path.join(repoRoot, "skills/crisp-ui/SKILL.md")
export const SNIPPET_PATH = path.join(appRoot, "public/agents-snippet.md")
export const DOC_PATH = path.join(appRoot, "content/docs/ai.mdx")
export const ROOT_REGISTRY_PATH = path.join(repoRoot, "registry.json")

// Where the GitHub registry lives: `shadcn add <GITHUB_REPO>/<item>`.
export const GITHUB_REPO = "aristidesnakos/crisp-ui"

// The story that orders the items. A recommended path, not a standard.
export const STAGES = [
  { id: "see", name: "See", question: "What is happening?" },
  { id: "decide", name: "Decide", question: "What needs me, and who hears?" },
  { id: "act", name: "Act", question: "Do it safely." },
  { id: "confirm", name: "Confirm", question: "Did it work, who knows?" },
  { id: "record", name: "Record", question: "Can I prove who did what?" },
]
const stageIndex = (id) => STAGES.findIndex((s) => s.id === id)

/** Items from the template, origin baked in, validated, in story order. */
export function loadItems(templateText, origin = PRODUCTION_ORIGIN) {
  const template = JSON.parse(
    templateText.replaceAll("__REGISTRY_ORIGIN__", origin)
  )
  const items = template.items.map((item) => {
    const stage = item.meta?.stage
    if (stageIndex(stage) === -1) {
      throw new Error(
        `${item.name}: meta.stage must be one of ${STAGES.map((s) => s.id).join(", ")} (got ${JSON.stringify(stage)})`
      )
    }
    if (!item.description) throw new Error(`${item.name}: missing description`)
    return {
      name: item.name,
      title: item.title ?? item.name,
      description: item.description,
      stage,
      stageEnd: item.meta.stageEnd,
      installUrl: `${origin}/r/${item.name}.json`,
      docsUrl: item.meta.recipe ?? `${origin}/docs/components/${item.name}.md`,
    }
  })
  // Array.prototype.sort is stable: template order is kept within a stage.
  return items.sort((a, b) => stageIndex(a.stage) - stageIndex(b.stage))
}

const stageLabel = (item) =>
  item.stageEnd ? `${item.stage} to ${item.stageEnd}` : item.stage
const cell = (text) => text.replaceAll("|", "\\|")
const GENERATED =
  "<!-- Generated by apps/v4/scripts/build-agent-files.mjs from apps/v4/registry-crisp.template.json. Do not edit by hand; run `pnpm agent:build`. -->"

export function renderSkill(items, origin = PRODUCTION_ORIGIN) {
  const names = items.map((i) => i.name)
  const description =
    `Install and use crisp-ui, a shadcn registry of dashboard patterns for internal tools (${names.join(", ")}). ` +
    "Use when building an admin or internal-tool screen that shows how a job is going, lets a person choose who is notified and sends a message, " +
    "or when the user mentions crisp-ui or regularui.com. UI only: it does not provide a backend and does not make anything compliant."
  const example = items.find((i) => i.name === "status-notify") ?? items[0]

  const storyRows = STAGES.map((s) => {
    const inStage = items
      .filter((i) => i.stage === s.id)
      .map((i) => `\`${i.name}\``)
    return `| ${s.name} | ${s.question} | ${inStage.length ? inStage.join(", ") : "none yet"} |`
  })
  const itemRows = items.map(
    (i) =>
      `| \`${i.name}\` | ${stageLabel(i)} | ${cell(i.description)} | \`npx shadcn@latest add ${i.installUrl}\` | ${i.docsUrl} |`
  )

  return `---
name: crisp-ui
description: ${JSON.stringify(description)}
license: MIT
---

${GENERATED}

# crisp-ui

crisp-ui is a shadcn registry of dashboard patterns for internal tools. You install the source into the project with the stock \`shadcn\` CLI and then own it; there is no package to upgrade. It is UI only.

## Install

The project must already be set up with \`npx shadcn@latest init\`. Install an item by URL; its dependencies come with it:

\`\`\`bash
npx shadcn@latest add ${example.installUrl}
\`\`\`

Or register the namespace once in \`components.json\` and install by name:

\`\`\`json
{ "registries": { "@crisp": "${origin}/r/{name}.json" } }
\`\`\`

\`\`\`bash
npx shadcn@latest add @crisp/${example.name}
\`\`\`

To look before installing, run \`npx shadcn@latest view ${example.installUrl}\` (prints the item JSON) or add \`--dry-run\` to \`add\` (lists the files and dependencies it would write, writes nothing).

## The story

Pick items in this order. It is a recommended path for a workflow screen, not a standard, and not every screen needs every stage.

**See, Decide, Act, Confirm, Record**, and back to See.

| Stage | Question | Items |
| --- | --- | --- |
${storyRows.join("\n")}

## Items

| Item | Stage | What it is | Install | Docs |
| --- | --- | --- | --- | --- |
${itemRows.join("\n")}

Each item's JSON at \`${origin}/r/<item>.json\` also carries \`categories\`, \`meta.stage\`, \`meta.recipe\` (its docs URL) and a short \`docs\` note.

## Rules

1. **Read the installed file before using it.** Take imports, prop names and types from the file in the project (import paths follow the aliases in \`components.json\`), not from memory or from this skill. Do not invent props; if a prop you want is missing, say so.
2. **UI only.** These parts render state and call handlers you supply (for example \`onSave\`, \`onSend\`). Sending, storage, access control, retention and consent belong to the project's backend. Do not imply a part does them.
3. **Email-only contacts.** A person is an email address, validated as one (override with the \`validate\` or \`validateEmail\` prop to match the backend). The channels are per-person switches, not phone numbers. Do not add phone or SMS contacts; if the user needs them, tell them these parts do not support that yet.
4. **Never claim compliance.** crisp-ui does not make a tool compliant with any law or standard. Do not write that it does, in code, comments, copy or answers.
5. **Verify.** After installing and wiring, run the project's typechecker (for example \`npx tsc --noEmit\`) and show the output.

## More

- Site index for agents: ${origin}/llms.txt
- Each docs page as markdown: ${origin}/docs/components/<item>.md
- Registry item JSON: ${origin}/r/<item>.json
- Setup guide: ${origin}/docs/ai
`
}

export function renderSnippet(items, origin = PRODUCTION_ORIGIN) {
  const example = items.find((i) => i.name === "status-notify") ?? items[0]
  const list = items.map(
    (i) => `- \`${i.name}\` (${stageLabel(i)}): ${i.description}`
  )
  return `<!-- crisp-ui:start (generated by apps/v4/scripts/build-agent-files.mjs; re-copy from ${origin}/agents-snippet.md) -->

## crisp-ui

crisp-ui is a shadcn registry of dashboard patterns for internal tools. UI only. Index for agents: ${origin}/llms.txt

Install: \`npx shadcn@latest add ${origin}/r/<item>.json\`, for example \`npx shadcn@latest add ${example.installUrl}\`. Docs for an item: \`${origin}/docs/components/<item>.md\`.

Story order: See, Decide, Act, Confirm, Record. Items:

${list.join("\n")}

Rules:

- Read the installed file before using it; use only the props it exports.
- UI only: sending, storage, access control and consent belong to the backend.
- Contacts are email addresses only. Do not add phone or SMS contacts.
- Never claim that crisp-ui makes an app compliant with any law or standard.
- After wiring, run the typechecker and show its output.

<!-- crisp-ui:end -->
`
}

/** Replaces the fenced copy of the snippet between the markers in ai.mdx. */
export function syncDoc(doc, snippet) {
  const start = "{/* agents-snippet:start */}"
  const end = "{/* agents-snippet:end */}"
  const from = doc.indexOf(start)
  const to = doc.indexOf(end)
  if (from === -1 || to < from) {
    throw new Error(`ai.mdx needs ${start} and ${end} around the snippet`)
  }
  return `${doc.slice(0, from + start.length)}\n\n\`\`\`markdown\n${snippet.trimEnd()}\n\`\`\`\n\n${doc.slice(to)}`
}

/**
 * The template as a root registry.json for GitHub installs. Differences from the
 * hosted registry: file paths are relative to the repository root, and sibling
 * dependencies are `owner/repo/item` (resolved on the default branch) instead of
 * URLs on the registry origin. Links to the docs point at production.
 */
export function renderRootRegistry(templateText) {
  const registry = JSON.parse(
    templateText
      .replaceAll(`${ORIGIN_TOKEN}/docs`, `${PRODUCTION_ORIGIN}/docs`)
      .replace(
        new RegExp(`${ORIGIN_TOKEN}/r/([a-z0-9-]+)\\.json`, "g"),
        `${GITHUB_REPO}/$1`
      )
      .replaceAll(ORIGIN_TOKEN, PRODUCTION_ORIGIN)
  )
  for (const item of registry.items) {
    for (const file of item.files) file.path = `apps/v4/${file.path}`
  }
  return `${JSON.stringify(registry, null, 2)}\n`
}

export function buildAll(templateText = readFileSync(TEMPLATE_PATH, "utf8")) {
  const items = loadItems(templateText)
  const snippet = renderSnippet(items)
  return [
    { file: SKILL_PATH, content: renderSkill(items) },
    { file: SNIPPET_PATH, content: snippet },
    {
      file: DOC_PATH,
      content: syncDoc(readFileSync(DOC_PATH, "utf8"), snippet),
    },
    { file: ROOT_REGISTRY_PATH, content: renderRootRegistry(templateText) },
  ]
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = buildAll()
  if (process.argv.includes("--check")) {
    const stale = outputs.filter((o) => {
      try {
        return readFileSync(o.file, "utf8") !== o.content
      } catch {
        return true
      }
    })
    if (stale.length) {
      console.error(
        `out of date, run \`pnpm agent:build\`:\n  ${stale.map((o) => path.relative(repoRoot, o.file)).join("\n  ")}`
      )
      process.exit(1)
    }
    console.log("agent files are up to date")
  } else {
    for (const { file, content } of outputs) {
      mkdirSync(path.dirname(file), { recursive: true })
      writeFileSync(file, content)
      console.log(`wrote ${path.relative(repoRoot, file)}`)
    }
  }
}
